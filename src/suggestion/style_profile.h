// style_profile.h
#pragma once

#include <QColor>
#include <QString>
#include <QVector>

// Стилевой профиль: описание стиля генерации + пользовательские веса.
// Чистые данные — без виджетов и без состояния приложения.
//
// Именование (юридические оговорки ТЗ): имена исторических авторов
// (Пушкин, Тютчев — давние умершие, произведения в общественном
// достоянии) используются как описательные названия. Для живых
// авторов и публичных персон имя как коммерческое название профиля
// НЕ используется — только нейтральные описательные имена вроде
// «Официальный стиль» или «Киберпанк 80-х».
//
// Вес: 0..1 (сырой, до нормализации; применяется StyleMixer —
// нормализованные веса активных профилей в сумме дают ровно 1.0).
// enabled=false — профиль не участвует, каким бы ни был вес.
struct StyleProfile
{
    // Стабильный ASCII-идентификатор (для QSettings/контрактов).
    QString id;
    // Человеческое имя — показывается в UI, входит в prompt-инструкцию.
    QString displayName;
    // Короткое описание — для списка в UI (в prompt не попадает).
    QString description;
    // Цвет индикатора профиля в UI (на генерацию не влияет).
    QColor color;
    // Одна компактная инструкция для модели — единственный текст
    // профиля, попадающий в prompt (короткий по контракту — prompt
    // не разрастается).
    QString promptInstruction;
    // Сырой вес 0..1; 0 => профиль неактивен для prompt'а.
    double weight = 0.0;
    // Выключен => не участвует независимо от веса.
    bool enabled = true;
};

// Встроенные профили (Пушкин, Тютчев, «Киберпанк 80-х»,
// «Официальный стиль»). Идемпотентно: каждый вызов возвращает новый
// список со значениями по умолчанию (вес 0, включены) — мутировать
// нужно копию, хранимое состояние приложения от этого не зависит.
QVector<StyleProfile> builtinStyleProfiles();
