// style_profile.h
#pragma once

#include "backend/text_generation_backend.h" // StyleWeight (findActiveAdapter)

#include <QColor>
#include <QString>
#include <QVector>

// Стилевой профиль: описание стиля генерации + пользовательские веса.
// Чистые данные — без виджетов и без состояния приложения.
//
// Именование (юридические оговорки ТЗ): имена исторических авторов
// (Пушкин, Тютчев — давние умершие, произведения в общественном
// достоянии) используются как описательные названия. Для живых
// авторов и публичных персон имя как коммерческое название профиля
// НЕ используется — только нейтральные описательные имена вроде
// «Официальный стиль» или «Киберпанк 80-х».
//
// Вес: 0..1 (сырой, до нормализации; применяется StyleMixer —
// нормализованные веса активных профилей в сумме дают ровно 1.0).
// enabled=false — профиль не участвует, каким бы ни был вес.
//
// --- Опциональные поля под будущие LoRA-адаптеры -------------------------
// MVP адаптеров НЕ использует: смешивание стилей идёт только через
// prompt (нормализованные веса StyleMixer + инструкция PromptBuilder),
// а настоящее наложение LoRA-адаптеров требует отдельного inference
// backend'а (см. README, раздел «Стили и LoRA-адаптеры»).
//
// Нейтральность: только Qt-типы (QString/double) — никаких типов,
// классов и путей библиотек обучения (peft, transformers, llama-lora
// и т.п.). Из-за этого StylePanel и PromptBuilder о полях адаптеров
// знают ровно настолько, чтобы НЕ зависеть от них: панель отображает
// только нейтральные поля, PromptBuilder в prompt их не включает.
//
// Пустой adapterPath = адаптера нет; остальные поля в этом случае
// игнорируются (значения по умолчанию нейтральны — текущий
// GGUF-бэкенд работает без изменений).
struct StyleProfile
{
    // Стабильный ASCII-идентификатор (для QSettings/контрактов).
    QString id;
    // Человеческое имя — показывается в UI, входит в prompt-инструкцию.
    QString displayName;
    // Короткое описание — для списка в UI (в prompt не попадает).
    QString description;
    // Цвет индикатора профиля в UI (на генерацию не влияет).
    QColor color;
    // Одна компактная инструкция для модели — единственный текст
    // профиля, попадающий в prompt (короткий по контракту — prompt
    // не разрастается).
    QString promptInstruction;
    // Сырой вес 0..1; 0 => профиль неактивен для prompt'а.
    double weight = 0.0;
    // Выключен => не участвует независимо от веса.
    bool enabled = true;

    // Путь к файлу адаптера (пусто = адаптера нет). Будущий
    // adapter-capable backend грузит его сам; текущие бэкенды обязаны
    // отвечать явной ошибкой (см. ITextGenerationBackend::supportsAdapters).
    QString adapterPath;
    // Свободный тег формата: "lora", "dora", ... — нейтральная строка,
    // никакой привязки к конкретной библиотеке/формату хранения.
    QString adapterType;
    // Идентификатор базовой модели, под которую обучен адаптер;
    // сверяется с базовой моделью backend'а (checkAdapterCompatibility).
    QString baseModelId;
    // Триггер-метка в prompt для совместимых inference-бэкендов.
    // PromptBuilder (MVP) её НЕ включает — это часть adapter-пути.
    QString promptTag;
    // Сила применения адаптера (типично 0..1); интерпретация и
    // ограничение диапазона — за бэкендом. Игнорируется без adapterPath.
    double adapterScale = 1.0;
};

// Встроенные профили (Пушкин, Тютчев, «Киберпанк 80-х»,
// «Официальный стиль»). Идемпотентно: каждый вызов возвращает новый
// список со значениями по умолчанию (вес 0, включены) — мутировать
// нужно копию, хранимое состояние приложения от этого не зависит.
// Адаптеры не объявлены ни у одного встроенного профиля.
QVector<StyleProfile> builtinStyleProfiles();

// Объявлен ли у профиля адаптер (непустой adapterPath).
bool hasAdapter(const StyleProfile& profile);

// Проверка совместимости адаптера профиля с базовой моделью backend'а.
// Чистая функция на Qt-типах — без библиотек обучения. Возвращает
// пустую строку, если проверять нечего (адаптера нет) или всё
// совместимо; иначе — текст ошибки для показа пользователю.
//
// Строгая семантика (проверять ДО инференса, а не после):
//  - адаптера нет                       -> пустая строка (нечего проверять);
//  - у адаптера не указан baseModelId   -> ошибка: не проверено;
//  - базовая модель backend'а неизвестна-> ошибка: не проверено;
//  - идентификаторы различаются         -> ошибка несовместимости;
//    (без учёта регистра)
//  - совпадение                         -> пустая строка (совместимо).
// Идентификаторы сравниваются как есть: бэкенд и адаптеры должны
// пользоваться одной системой идентификаторов (см. README).
QString checkAdapterCompatibility(const StyleProfile& profile,
                                  const QString& backendBaseModelId);

// Первый активный профиль, объявляющий адаптер, из списка профилей и
// нормализованных весов активных стилей (как в GenerationRequest).
// Активен = hasAdapter && enabled && встречается в activeWeights с
// весом > 0. nullptr = активных адаптеров нет. (В MVP активный
// адаптер — ошибка запроса: см. SuggestionController::startRequest.)
const StyleProfile* findActiveAdapter(
    const QVector<StyleProfile>& profiles,
    const QVector<StyleWeight>& activeWeights);
